export type TranslationKey = keyof typeof TRANSLATIONS.ko;

function detectInitialLang(): SupportedLang {
  const injected = (window as unknown as { __ERMASTER_LANG__?: string }).__ERMASTER_LANG__;
  if (injected === 'ko' || injected === 'en' || injected === 'ja') {
    return injected;
  }
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('ko')) return 'ko';
  if (nav.startsWith('ja')) return 'ja';
  return 'en';
}

let currentLang: SupportedLang = detectInitialLang();
const listeners = new Set<(lang: SupportedLang) => void>();

export function setGlobalLang(lang: SupportedLang): void {
  if (currentLang === lang) return;
  currentLang = lang;
  for (const fn of listeners) {
    fn(lang);
  }
}

export function getGlobalLang(): SupportedLang {
  return currentLang;
}

export function translate(key: TranslationKey, lang: SupportedLang = currentLang): string {
  return TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key] ?? key;
}

export function useI18n() {
  const [lang, setLang] = useState<SupportedLang>(currentLang);

  useEffect(() => {
    const onChange = (next: SupportedLang) => setLang(next);
    listeners.add(onChange);

    const onMessage = (event: MessageEvent) => {
      const msg = event.data;
      if (msg?.type === 'setLanguage' && (msg.lang === 'ko' || msg.lang === 'en' || msg.lang === 'ja')) {
        setGlobalLang(msg.lang);
      }
    };
    window.addEventListener('message', onMessage);

    return () => {
      listeners.delete(onChange);
      window.removeEventListener('message', onMessage);
    };
  }, []);

  return {
    lang,
    t: (key: TranslationKey) => translate(key, lang)
  };
}
